import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const dir=path.dirname(fileURLToPath(import.meta.url));
const [id,reason]=process.argv.slice(2);
assert.match(id,/^I\d{3}$/);assert.ok(reason);
const read=f=>fs.readFileSync(path.join(dir,f),'utf8');
const write=(f,v)=>fs.writeFileSync(path.join(dir,f),JSON.stringify(v,null,2)+'\n');
const b=JSON.parse(read('storyboard.json'));const s=b.scenes.find(s=>s.id===id);
assert.ok(s);assert.ok(!s.file.endsWith('-v2.png'));
const old=s.file;
s.versions=[...(s.versions??[]),{file:old,status:'rejected',reason,qa:s.qa,source:s.source}];
s.file=old.replace('.png','-v2.png');s.status='needs-revision';s.qa=null;s.source=null;
s.revisionPromptFile='productions/'+b.slug+'/'+id+'.revision-prompt.txt';
write('storyboard.json',b);
const sentences=JSON.parse(read('sentences.json'));sentences.sentences.find(x=>x.imageId===id).file=s.file;write('sentences.json',sentences);
const p=read('prompts.jsonl').trim().split('\n').map(JSON.parse);p.find(x=>x.id===id).file=s.file;
fs.writeFileSync(path.join(dir,'prompts.jsonl'),p.map(JSON.stringify).join('\n')+'\n');
fs.writeFileSync(path.join(dir,'image_prompts.md'),read('image_prompts.md').replace('Đích: '+old,'Đích: '+s.file));
const m=JSON.parse(read('manifest.json'));
m.stages.images.outputs=b.scenes.filter(s=>['generated','verified'].includes(s.status)).map(s=>s.file);
m.progress={...m.progress,generatedImages:m.stages.images.outputs.length,verifiedImages:b.scenes.filter(s=>s.status==='verified').length,remainingImages:260-m.stages.images.outputs.length,nextImage:id};
write('manifest.json',m);
fs.appendFileSync(path.join(dir,'qa.md'),'\n- '+id+' initial version rejected: '+reason+'\n');
